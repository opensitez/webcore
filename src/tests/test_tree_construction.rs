//! Tree-construction conformance — OUR OWN suite.
//!
//! Each case is a fragment of markup and the DOM a browser builds from it. The
//! expectations were generated from `Chrome --headless --dump-dom` by
//! `/tmp/webcore-html/gen/gen.py`, so they are the real answer rather than what
//! this parser happens to do; regenerate them the same way when adding cases.
//!
//! The comparison is a CANONICAL TREE: one line per node, two spaces of indent
//! per level, `tag[attr=value,…]` with attributes sorted, `"text"` for a text
//! run, `<!--data-->` for a comment. Whitespace-only text is dropped and text
//! runs are collapsed — webcore collapses whitespace at PARSE time and a
//! browser does it at layout time, so comparing it verbatim would fail on a
//! difference that is not a defect. Structure, attributes and visible text are
//! what this pins down, which is exactly where the tree-construction bugs live.
//!
//! An external suite (html5lib-tests) is the eventual goal; this is ours until
//! then, and it stays useful afterwards because it is small enough to read.

use crate::parse_html;
use crate::types::WebCore;

/// Render one node in the canonical form described above.
fn canon_into(node: &WebCore, depth: usize, out: &mut String) {
    let pad = "  ".repeat(depth);
    if node.is_pseudo_element() {
        return;
    } // generated content is not a node
    if node.tag == "#text" {
        let t: Vec<&str> = node.text.split_whitespace().collect();
        if !t.is_empty() {
            out.push_str(&format!("{}\"{}\"\n", pad, t.join(" ")));
        }
        return;
    }
    if node.tag == "#comment" {
        let t: Vec<&str> = node.text.split_whitespace().collect();
        out.push_str(&format!("{}<!--{}-->\n", pad, t.join(" ")));
        return;
    }
    let mut attrs: Vec<(&String, &String)> = node.attributes.iter().collect();
    attrs.sort_by(|a, b| a.0.cmp(b.0));
    let a = if attrs.is_empty() {
        String::new()
    } else {
        format!(
            "[{}]",
            attrs
                .iter()
                .map(|(k, v)| format!("{}={}", k, v))
                .collect::<Vec<_>>()
                .join(",")
        )
    };
    out.push_str(&format!("{}{}{}\n", pad, node.tag, a));
    // An element's OWN text is emitted as a text child. webcore keeps the
    // content of `<style>`, `<title>` and `<textarea>` on the element rather
    // than in a child node — an internal choice — but the DOM those elements
    // present has one text child, and that is what a browser reports. Modelling
    // it here keeps this suite about TREE CONSTRUCTION; that `childNodes` does
    // not yet report it is an interface gap tracked separately.
    if !node.text.is_empty() && node.tag != "#text" {
        let t: Vec<&str> = node.text.split_whitespace().collect();
        if !t.is_empty() {
            out.push_str(&format!("{}  \"{}\"\n", pad, t.join(" ")));
        }
    }
    for c in &node.children {
        canon_into(c, depth + 1, out);
    }
}

fn canon(html: &str) -> String {
    let doc = parse_html(html);
    let mut s = String::new();
    canon_into(&doc.root, 0, &mut s);
    s
}

fn find_tag<'a>(node: &'a WebCore, tag: &str) -> Option<&'a WebCore> {
    if node.tag == tag {
        return Some(node);
    }
    node.children.iter().find_map(|child| find_tag(child, tag))
}

#[test]
fn inline_svg_projects_native_children_into_the_tree() {
    let doc = parse_html(
        r##"<svg width="16" height="16"><g id="icon"><path xlink:href="#p" d="M0 0h10v10z"/></g></svg>"##,
    );
    let svg = find_tag(&doc.root, "svg").expect("svg node");
    let group = svg
        .children
        .iter()
        .find(|child| child.tag == "g")
        .expect("g child");
    let path = group
        .children
        .iter()
        .find(|child| child.tag == "path")
        .expect("path child");
    assert!(svg.svg_document.is_some());
    assert_eq!(group.attributes.get("id").map(String::as_str), Some("icon"));
    assert_eq!(
        path.attributes.get("xlink:href").map(String::as_str),
        Some("#p")
    );
}

